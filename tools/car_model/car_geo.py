def cyl_solid(r, depth, res=28, axis='y', c=(0.0, 0.0, 0.0)):
    """use_caps 로 만든 원통을 단순 피라미드 캡으로 직접 구성한 매니폴드."""
    half = depth * 0.5
    verts, faces = [], []
    ring = []
    for sgn in (-1, 1):
        blk = []
        for i in range(res):
            a = 2.0 * math.pi * i / res
            u, v = r * math.cos(a), r * math.sin(a)
            if axis == 'y':
                p = (c[0] + u, c[1] + sgn * half, c[2] + v)
            elif axis == 'x':
                p = (c[0] + sgn * half, c[1] + u, c[2] + v)
            else:
                p = (c[0] + u, c[1] + v, c[2] + sgn * half)
            blk.append(len(verts))
            verts.append(p)
        ring.append(blk)
    a0, a1 = ring
    for i in range(res):
        i2 = (i + 1) % res
        faces.append((a0[i], a0[i2], a1[i2], a1[i]))
    for bi, blk in ((0, a0), (1, a1)):
        for i in range(1, res - 1):
            if bi == 0:
                faces.append((blk[0], blk[i], blk[i + 1]))
            else:
                faces.append((blk[0], blk[i + 1], blk[i]))
    return verts, faces


def box_pydata(sx, sy, sz, c=(0.0, 0.0, 0.0), rot_z=0.0):
    """회전된 박스 (verts, faces)."""
    hx, hy, hz = sx * 0.5, sy * 0.5, sz * 0.5
    raw = [(-hx, -hy, -hz), (hx, -hy, -hz), (hx, hy, -hz), (-hx, hy, -hz),
           (-hx, -hy, hz), (hx, -hy, hz), (hx, hy, hz), (-hx, hy, hz)]
    ca, sa = math.cos(rot_z), math.sin(rot_z)
    verts = []
    for (x, y, z) in raw:
        verts.append((c[0] + x * ca - y * sa, c[1] + x * sa + y * ca, c[2] + z))
    faces = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5),
             (2, 3, 7, 6), (3, 0, 4, 7)]
    return verts, faces


def taper_cyl_pydata(r0, r1, depth, res=24, axis='y', c=(0.0, 0.0, 0.0)):
    """양 끝 반지름이 다른 원뿔대 (브레이크 디스크/드럼)."""
    half = depth * 0.5
    verts, ring = [], []
    for (rr, sgn) in ((r0, -1), (r1, 1)):
        blk = []
        for i in range(res):
            a = 2.0 * math.pi * i / res
            u, v = rr * math.cos(a), rr * math.sin(a)
            if axis == 'y':
                p = (c[0] + u, c[1] + sgn * half, c[2] + v)
            else:
                p = (c[0] + u, c[1] + v, c[2] + sgn * half)
            blk.append(len(verts))
            verts.append(p)
        ring.append(blk)
    a0, a1 = ring
    faces = []
    for i in range(res):
        i2 = (i + 1) % res
        faces.append((a0[i], a0[i2], a1[i2], a1[i]))
    for blk in ring:
        for i in range(1, res - 1):
            faces.append((blk[0], blk[i + 1], blk[i]))
    return verts, faces


