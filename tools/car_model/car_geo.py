#  단면 / 로프트
# ---------------------------------------------------------------------------
def ring_pts(rx, rz, cz, p, n=20, y0=0.0):
    """superellipse 단면 점 목록 ((0,y,z), ...) - 시계방향(y->z)"""
    e = 2.0 / p
    pts = []
    for i in range(n):
        t = 2.0 * math.pi * i / n
        c, s = math.cos(t), math.sin(t)
        y = y0 + rx * math.copysign(abs(c) ** e, c)
        z = cz + rz * math.copysign(abs(s) ** e, s)
        pts.append((0.0, y, z))
    return pts


def loft(rings_data, n=20):
    """[(x, rx, rz, cz, p)] -> (verts, faces) 닫힌 매니폴드. 면노름은 바깥."""
    rings = []
    for (x, rx, rz, cz, p) in rings_data:
        for (dummy, y, z) in ring_pts(rx, rz, cz, p, n):
            rings.append((x, y, z))
    verts = list(rings)
    faces = []
    nr = len(rings_data)
    for r in range(nr - 1):
        a = r * n
        b = (r + 1) * n
        for i in range(n):
            i2 = (i + 1) % n
            faces.append((a + i, a + i2, b + i2, b + i))
    faces.append(tuple(r * n + i for i in reversed(range(n))))
    faces.append(tuple((nr - 1) * n + i for i in range(n)))
    return verts, faces


